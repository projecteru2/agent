func TestWithTimeout(t *testing.T) {
	ctx := t.Context()
	i := 0
	WithTimeout(ctx, time.Second, func(ctx context.Context) {
		select {
		case <-ctx.Done():
			return
		default:
			i = 1
		}
	})

	assert.Equal(t, i, 1)

	WithTimeout(ctx, time.Second, func(ctx context.Context) {
		time.Sleep(2 * time.Second)
		select {
		case <-ctx.Done():
			return
		default:
			i = 2
		}
	})

	assert.NotEqual(t, i, 2)
}
